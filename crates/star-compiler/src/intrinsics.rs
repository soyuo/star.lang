    /// Resolves a source mnemonic to its IR operation.
    pub fn from_mnemonic(mnemonic: &str) -> Option<Self> {
        (0..100)
            .filter_map(|index| Self::from_intrinsic_id(0x8000 + index))
            .find(|operation| operation.mnemonic() == mnemonic)
    }

